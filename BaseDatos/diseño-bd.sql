-- Archivo : diseño-bd.sql
-- Motor   : PostgreSQL (probado en PostgreSQL 16)
-- Objetivo: modelo de datos de un parqueo de automóviles.
--           Tablas con prefijo PRQ:
--             prq_automovil          (Automóviles)
--             prq_parqueo            (Parqueo)
--             prq_ingreso_automovil  (Ingreso de automóviles)
--
-- Decisiones de diseño (no definidas por el enunciado):
--   * Los identificadores se escriben en minúscula y sin comillas, que es
--     la forma en que PostgreSQL los almacena (PRQ_AUTOMOVIL = prq_automovil).
--     Así el scaffold de EF Core y las consultas no requieren comillas.
--   * Nombres de tabla en singular para que el scaffold genere clases
--     legibles (PrqAutomovil, PrqParqueo, PrqIngresoAutomovil).
--   * El tipo de automóvil (sedán, 4x4, moto) se valida con una
--     restricción CHECK sobre varchar en lugar de un ENUM nativo de
--     PostgreSQL: evita el problema de mapeo de enums de Npgsql visto en
--     la clase 6 y no agrega una cuarta tabla que el enunciado no pide.
--   * Las fechas usan "timestamp without time zone": el parqueo opera en
--     una sola zona horaria (Costa Rica, UTC-6, sin horario de verano) y
--     se evita la conversión obligatoria a UTC de Npgsql.
--   * El precio por hora usa numeric(10,2): tipo exacto para dinero.
--   * Las claves foráneas usan ON DELETE RESTRICT: no se puede borrar un
--     automóvil o parqueo que tenga ingresos registrados.
--
-- Antes de ejecutar en la instancia en la nube, verifique dónde se crearán
-- los objetos (base, esquema y usuario):
--     SELECT current_database(), current_schema(), current_user;
-- El script NO borra objetos existentes. Si una tabla ya existe, la
-- transacción falla completa y no deja cambios parciales.
-- =====================================================================

SET client_encoding = 'UTF8';

BEGIN;

-- ---------------------------------------------------------------------
-- Tabla A: Automóviles
-- ---------------------------------------------------------------------
CREATE TABLE prq_automovil (
    id          integer      GENERATED BY DEFAULT AS IDENTITY,
    color       varchar(30)  NOT NULL,
    anio        integer      NOT NULL,
    fabricante  varchar(50)  NOT NULL,
    tipo        varchar(10)  NOT NULL,
    CONSTRAINT pk_prq_automovil PRIMARY KEY (id),
    CONSTRAINT ck_prq_automovil_color_no_vacio CHECK (btrim(color) <> ''),
    CONSTRAINT ck_prq_automovil_fabricante_no_vacio CHECK (btrim(fabricante) <> ''),
    CONSTRAINT ck_prq_automovil_anio CHECK (anio BETWEEN 1886 AND 2100),
    CONSTRAINT ck_prq_automovil_tipo CHECK (tipo IN ('sedán', '4x4', 'moto'))
);

COMMENT ON TABLE  prq_automovil            IS 'Automóviles que utilizan los parqueos.';
COMMENT ON COLUMN prq_automovil.id         IS 'Llave primaria del automóvil.';
COMMENT ON COLUMN prq_automovil.color      IS 'Color del automóvil.';
COMMENT ON COLUMN prq_automovil.anio       IS 'Año (modelo) del automóvil.';
COMMENT ON COLUMN prq_automovil.fabricante IS 'Fabricante o marca del automóvil.';
COMMENT ON COLUMN prq_automovil.tipo       IS 'Tipo de automóvil: sedán, 4x4 o moto.';

-- ---------------------------------------------------------------------
-- Tabla B: Parqueo
-- ---------------------------------------------------------------------
CREATE TABLE prq_parqueo (
    id                integer        GENERATED BY DEFAULT AS IDENTITY,
    nombre_provincia  varchar(20)    NOT NULL,
    nombre            varchar(100)   NOT NULL,
    precio_por_hora   numeric(10, 2) NOT NULL,
    CONSTRAINT pk_prq_parqueo PRIMARY KEY (id),
    CONSTRAINT ck_prq_parqueo_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_prq_parqueo_provincia CHECK (nombre_provincia IN
        ('San José', 'Alajuela', 'Cartago', 'Heredia', 'Guanacaste', 'Puntarenas', 'Limón')),
    CONSTRAINT ck_prq_parqueo_precio_por_hora CHECK (precio_por_hora > 0)
);

COMMENT ON TABLE  prq_parqueo                  IS 'Parqueos (estacionamientos) disponibles.';
COMMENT ON COLUMN prq_parqueo.id               IS 'Llave primaria del parqueo.';
COMMENT ON COLUMN prq_parqueo.nombre_provincia IS 'Provincia de Costa Rica donde se ubica el parqueo.';
COMMENT ON COLUMN prq_parqueo.nombre           IS 'Nombre del parqueo.';
COMMENT ON COLUMN prq_parqueo.precio_por_hora  IS 'Tarifa por hora en colones.';

-- ---------------------------------------------------------------------
-- Tabla C: Ingreso de automóviles
-- fecha_hora_salida en NULL significa que el automóvil aún no ha salido.
-- ---------------------------------------------------------------------
CREATE TABLE prq_ingreso_automovil (
    consecutivo         integer    GENERATED BY DEFAULT AS IDENTITY,
    id_parqueo          integer    NOT NULL,
    id_automovil        integer    NOT NULL,
    fecha_hora_entrada  timestamp  NOT NULL,
    fecha_hora_salida   timestamp  NULL,
    CONSTRAINT pk_prq_ingreso_automovil PRIMARY KEY (consecutivo),
    CONSTRAINT fk_prq_ingreso_automovil_parqueo FOREIGN KEY (id_parqueo)
        REFERENCES prq_parqueo (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_prq_ingreso_automovil_automovil FOREIGN KEY (id_automovil)
        REFERENCES prq_automovil (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_prq_ingreso_automovil_salida_posterior
        CHECK (fecha_hora_salida IS NULL OR fecha_hora_salida > fecha_hora_entrada)
);

COMMENT ON TABLE  prq_ingreso_automovil                    IS 'Registro de ingresos y salidas de automóviles en los parqueos.';
COMMENT ON COLUMN prq_ingreso_automovil.consecutivo        IS 'Llave primaria consecutiva del ingreso.';
COMMENT ON COLUMN prq_ingreso_automovil.id_parqueo         IS 'Parqueo al que ingresó el automóvil.';
COMMENT ON COLUMN prq_ingreso_automovil.id_automovil       IS 'Automóvil que ingresó.';
COMMENT ON COLUMN prq_ingreso_automovil.fecha_hora_entrada IS 'Fecha y hora de entrada.';
COMMENT ON COLUMN prq_ingreso_automovil.fecha_hora_salida  IS 'Fecha y hora de salida; NULL si el automóvil no ha salido.';

-- Índices de apoyo para las claves foráneas y las consultas por intervalo.
CREATE INDEX ix_prq_ingreso_automovil_id_parqueo   ON prq_ingreso_automovil (id_parqueo);
CREATE INDEX ix_prq_ingreso_automovil_id_automovil ON prq_ingreso_automovil (id_automovil);
CREATE INDEX ix_prq_ingreso_automovil_entrada      ON prq_ingreso_automovil (fecha_hora_entrada);

COMMIT;
